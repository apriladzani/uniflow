export type AuthLang = 'en' | 'id';

const STORAGE_KEY = 'uim_auth_lang';

export function readAuthLang(): AuthLang {
  try { return localStorage.getItem(STORAGE_KEY) === 'id' ? 'id' : 'en'; } catch { return 'en'; }
}

export function saveAuthLang(lang: AuthLang) {
  try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* storage is optional */ }
}

